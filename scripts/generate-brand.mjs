// Export only approved color leaves; proposed typography/layout tokens never enter runtime.
import fs from 'node:fs'
const tokens = JSON.parse(fs.readFileSync(new URL('../brand/tokens/brand.tokens.json', import.meta.url)))
const colors = Object.entries(tokens.color).map(([name, token]) => {
  if (token.$extensions.nexus.status !== 'approved') throw new Error(`Unapproved color: ${name}`)
  return `  --nexus-${name}: ${token.$value};`
})
fs.writeFileSync(new URL('../src/slate.tokens.css', import.meta.url), `/* Generated by scripts/generate-brand.mjs. */\n:root {\n${colors.join('\n')}\n}\n`)
fs.copyFileSync(new URL('../brand/assets/approved/n-dot.svg', import.meta.url), new URL('../public/brand/nexus-app-icon.svg', import.meta.url))
